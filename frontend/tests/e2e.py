"""Optional browser integration checks.

With both servers running: python frontend/tests/e2e.py
Requires: pip install playwright && python -m playwright install chromium
"""
from pathlib import Path
import json
import re
from playwright.sync_api import sync_playwright, expect

OUT = Path(__file__).resolve().parents[1] / "test-results"
OUT.mkdir(exist_ok=True)


def main():
    errors = []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True)
        context = browser.new_context(viewport={"width":1440,"height":1100}, device_scale_factor=1)
        page = context.new_page()
        creations = []
        page.on("request",lambda req: creations.append(req.url) if req.method=="POST" and req.url.endswith("/api/games") else None)
        page.on("pageerror",lambda error: errors.append(str(error)))
        page.goto("http://127.0.0.1:5173")
        expect(page.get_by_role("grid")).to_be_visible()
        expect(page.locator(".cell")).to_have_count(225)
        expect(page.locator(".mode-option")).to_have_count(4)
        expect(page.get_by_text("Chơi online",exact=True)).to_be_visible()
        expect(page.locator(".ready-overlay")).to_be_visible()
        expect(page.get_by_role("gridcell",name="A1: ô trống",exact=True)).to_have_attribute("aria-disabled","true")
        page.get_by_role("gridcell",name="A1: ô trống",exact=True).click(force=True)
        page.wait_for_timeout(1200)
        expect(page.locator(".occupied")).to_have_count(0)
        assert not creations,"Opening the page must not create a game"
        assert page.locator("html").evaluate("el => getComputedStyle(el).getPropertyValue('--accent').trim()") == "#7c3aed"
        page.screenshot(path=str(OUT/"desktop.png"),full_page=True)
        page.locator(".start-button").click()
        expect(page.locator(".ready-overlay")).to_have_count(0)
        assert len(creations)==1
        print("PASS locked preview, explicit start, four modes, purple palette",flush=True)
        page.get_by_role("gridcell",name="H8: ô trống",exact=True).click()
        expect(page.locator(".occupied")).to_have_count(2,timeout=15000)
        page.get_by_role("button",name="Gợi ý",exact=True).click()
        expect(page.locator(".hint-cell")).to_have_count(1)
        page.get_by_role("button",name="Đi lại",exact=True).click()
        expect(page.locator(".occupied")).to_have_count(0)
        print("PASS AI turn, neural hint, paired undo",flush=True)

        page.locator(".mode-option").filter(has_text="Hai người").click()
        page.get_by_role("button",name="6×6",exact=True).click()
        page.locator(".win-options").get_by_role("button",name="4 quân",exact=True).click()
        page.locator(".start-button").click()
        expect(page.locator(".cell")).to_have_count(36)
        expect(page.locator(".board-caption")).to_contain_text("4 quân thắng")
        for coord in ["A1","A2","B1","B2","C1","C2","D1"]:
            page.get_by_role("gridcell",name=f"{coord}: ô trống",exact=True).click()
            expect(page.get_by_role("gridcell",name=f"{coord}: ô trống",exact=True)).to_have_count(0)
        expect(page.locator(".winning")).to_have_count(4)
        expect(page.locator(".finished-banner")).to_be_visible()
        page.screenshot(path=str(OUT/"local-win.png"),full_page=True)
        page.get_by_role("button",name="Thống kê",exact=True).click()
        expect(page.locator("tbody tr")).to_have_count(1)
        page.get_by_role("button",name="Xem lại",exact=False).click()
        expect(page.locator("dialog .occupied")).to_have_count(7)
        page.get_by_role("slider",name="Chọn nước đi").fill("0")
        expect(page.locator("dialog .occupied")).to_have_count(0)
        page.get_by_role("button",name="Đóng xem lại",exact=True).click()
        print("PASS quick winning length, four-in-row on 6x6, durable history, replay",flush=True)

        page.get_by_role("button",name="Hướng dẫn",exact=True).click()
        expect(page.locator(".guide-card")).to_have_count(6)
        page.get_by_role("button",name=re.compile("AI Lab")).first.click()
        expect(page.locator(".training-chart svg[role=img]")).to_be_visible()
        expect(page.get_by_text("34.250",exact=True)).to_be_visible()
        page.screenshot(path=str(OUT/"ai-lab.png"),full_page=True)
        page.get_by_role("button",name="Chuyển giao diện tối").click()
        expect(page.locator("html")).to_have_attribute("data-theme","dark")
        page.get_by_role("button",name="Chơi cờ",exact=True).click()
        page.screenshot(path=str(OUT/"dark.png"),full_page=True)
        page.get_by_role("button",name="Chuyển giao diện sáng").click()
        print("PASS guide, actual training chart, dark mode",flush=True)

        page.locator(".mode-option").filter(has_text="Hai người").click()
        page.get_by_role("button",name="Tùy chỉnh nâng cao").click()
        page.get_by_label("Kích thước tùy chỉnh").fill("25")
        page.get_by_role("dialog").get_by_label("Số quân để thắng").select_option("6")
        page.get_by_label("Luật thắng").select_option("blocked")
        page.get_by_role("button",name="Lưu thiết lập",exact=False).click()
        page.locator(".start-button").click()
        expect(page.locator(".cell")).to_have_count(625)
        expect(page.locator(".board-caption")).to_contain_text("6 quân thắng")
        page.get_by_role("gridcell",name="Y25: ô trống",exact=True).click()
        expect(page.get_by_role("gridcell",name="Y25: X",exact=True)).to_be_visible()
        print("PASS custom 25x25, six-in-row, blocked rule, corner move",flush=True)

        page.get_by_role("button",name="3×3",exact=True).click()
        expect(page.locator(".win-options").get_by_role("button",name="3 quân",exact=True)).to_have_attribute("aria-pressed","true")
        expect(page.locator(".win-options").get_by_role("button",name="4 quân",exact=True)).to_be_disabled()
        expect(page.locator(".win-options").get_by_role("button",name="6 quân",exact=True)).to_be_disabled()
        page.locator(".mode-option").filter(has_text="AI đấu AI").click()
        page.locator(".start-button").click()
        expect(page.locator(".occupied").first).to_be_visible(timeout=10000)
        page.get_by_role("button",name="Tạm dừng AI").click()
        expect(page.locator(".turn-banner")).to_contain_text("tạm dừng")
        page.wait_for_timeout(300)
        count=page.locator(".occupied").count()
        page.wait_for_timeout(1200)
        assert page.locator(".occupied").count()==count
        page.get_by_role("button",name="Tiếp tục AI").click()
        expect(page.locator(".occupied").nth(count)).to_be_visible(timeout=10000)
        print("PASS AI exhibition pause/resume",flush=True)

        before_reload = len(creations)
        page.reload()
        expect(page.locator(".ready-overlay")).to_be_visible()
        page.wait_for_timeout(1300)
        expect(page.locator(".occupied")).to_have_count(0)
        assert len(creations)==before_reload,"Reload must not restart AI exhibition"
        expect(page.get_by_role("button",name="Tạm dừng AI")).to_be_disabled()
        page.locator(".mode-option").filter(has_text="Đấu với AI").click()
        page.get_by_role("button",name="Tùy chỉnh nâng cao").click()
        page.get_by_label("Quân của bạn khi đấu AI").select_option("-1")
        page.get_by_label("Thời gian mỗi lượt").select_option("15")
        page.get_by_role("button",name="Lưu thiết lập",exact=False).click()
        page.wait_for_timeout(1200)
        expect(page.locator(".timer")).to_have_count(0)
        expect(page.locator(".occupied")).to_have_count(0)
        page.locator(".start-button").click()
        expect(page.locator(".occupied")).to_have_count(1,timeout=10000)
        expect(page.locator(".timer")).to_be_visible()
        page.get_by_role("button",name="Thiết lập lại ván cờ",exact=True).click()
        expect(page.locator(".ready-overlay")).to_be_visible()
        before_reset=len(creations)
        page.wait_for_timeout(1200)
        expect(page.locator(".occupied")).to_have_count(0)
        expect(page.locator(".timer")).to_have_count(0)
        assert len(creations)==before_reset,"Reset must wait for Start"
        print("PASS reload/reset stay idle; AI first move and timer require Start",flush=True)

        legacy_context=browser.new_context(viewport={"width":1280,"height":900})
        legacy_context.add_init_script("if (!localStorage.getItem('caro.config')) localStorage.setItem('caro.config', JSON.stringify({size:6,win_length:4,mode:'online',time_limit:15,player_name:'Chủ phòng'})); localStorage.setItem('caro.session', JSON.stringify({id:'old-room',token:'old-token'}));")
        legacy=legacy_context.new_page()
        legacy.on("pageerror",lambda error: errors.append(str(error)))
        legacy.goto("http://127.0.0.1:5173")
        expect(legacy.locator(".ready-overlay")).to_be_visible()
        expect(legacy.locator(".mode-option.selected")).to_contain_text("Chơi online")
        expect(legacy.locator(".mode-option")).to_have_count(4)
        expect(legacy.locator(".room-banner")).to_have_count(0)
        legacy.locator(".start-button").click()
        expect(legacy.locator(".waiting-code")).to_be_visible()
        expect(legacy.locator(".timer")).to_have_count(0)
        code=legacy.locator(".room-banner strong").inner_text()
        expect(legacy.locator(".room-banner small")).to_contain_text("Đã kết nối")
        guest_context=browser.new_context(viewport={"width":1280,"height":900})
        guest=guest_context.new_page()
        guest.on("pageerror",lambda error: errors.append(str(error)))
        guest.goto("http://127.0.0.1:5173")
        expect(guest.locator(".ready-overlay")).to_be_visible()
        guest.locator(".mode-option").filter(has_text="Chơi online").click()
        guest.get_by_role("button",name="Tham gia bằng mã phòng",exact=True).click()
        guest.get_by_role("dialog").get_by_label("Tên của bạn").fill("Người bạn")
        guest.get_by_label("Mã phòng").fill("000000")
        guest.get_by_role("button",name="Vào phòng",exact=True).click()
        expect(guest.locator(".form-error")).to_contain_text("không tồn tại")
        guest.get_by_label("Mã phòng").fill(code)
        guest.get_by_role("button",name="Vào phòng",exact=True).click()
        expect(guest.locator("dialog")).to_have_count(0)
        expect(guest.locator(".cell")).to_have_count(36)
        expect(guest.locator(".board-caption")).to_contain_text("4 quân thắng")
        expect(legacy.locator(".waiting-code")).to_have_count(0)
        expect(legacy.locator(".timer")).to_be_visible()
        expect(guest.locator(".room-banner small")).to_contain_text("Đã kết nối")
        expect(guest.get_by_role("gridcell",name="A1: ô trống",exact=True)).to_have_attribute("aria-disabled","true")
        legacy.get_by_role("gridcell",name="A1: ô trống",exact=True).click()
        expect(guest.get_by_role("gridcell",name="A1: X",exact=True)).to_be_visible(timeout=2000)
        guest.get_by_role("gridcell",name="A2: ô trống",exact=True).click()
        expect(legacy.get_by_role("gridcell",name="A2: O",exact=True)).to_be_visible(timeout=2000)
        expect(legacy.get_by_role("button",name="Đi lại",exact=True)).to_be_disabled()
        expect(legacy.get_by_role("button",name="Gợi ý",exact=True)).to_be_disabled()
        guest.reload()
        expect(guest.locator(".ready-overlay")).to_be_visible()
        expect(guest.locator(".occupied")).to_have_count(0)
        expect(guest.locator(".room-banner")).to_have_count(0)
        guest.route("**/api/games/*",lambda route: route.abort() if route.request.method=="GET" else route.continue_())
        guest.get_by_role("button",name="Kết nối lại phòng",exact=True).click()
        expect(guest.locator(".error-banner")).to_be_visible()
        expect(guest.get_by_role("button",name="Kết nối lại phòng",exact=True)).to_be_visible()
        guest.unroute("**/api/games/*")
        guest.get_by_role("button",name="Kết nối lại phòng",exact=True).click()
        expect(guest.get_by_role("gridcell",name="A1: X",exact=True)).to_be_visible()
        expect(guest.get_by_role("gridcell",name="A2: O",exact=True)).to_be_visible()
        expect(guest.locator(".room-banner small")).to_contain_text("Đã kết nối")
        for host_move,guest_move in [("B1","B2"),("C1","C2")]:
            legacy.get_by_role("gridcell",name=f"{host_move}: ô trống",exact=True).click()
            expect(guest.get_by_role("gridcell",name=f"{host_move}: X",exact=True)).to_be_visible(timeout=2000)
            guest.get_by_role("gridcell",name=f"{guest_move}: ô trống",exact=True).click()
            expect(legacy.get_by_role("gridcell",name=f"{guest_move}: O",exact=True)).to_be_visible(timeout=2000)
        legacy.get_by_role("gridcell",name="D1: ô trống",exact=True).click()
        expect(guest.locator(".winning")).to_have_count(4)
        expect(legacy.locator(".winning")).to_have_count(4)
        expect(guest.locator(".finished-banner")).to_contain_text("Chủ phòng")
        guest.wait_for_function("sessionStorage.getItem('caro.room-session') === null")
        legacy.screenshot(path=str(OUT/"online.png"),full_page=True)
        guest.locator(".finished-banner").get_by_role("button",name="Chơi tiếp",exact=False).click()
        expect(guest.locator(".ready-overlay")).to_be_visible()
        expect(guest.locator(".avatar")).to_have_text("N")
        print("PASS online rooms, invalid codes, websocket turns, explicit reconnect, custom target and shared result",flush=True)

        mobile_context=browser.new_context(viewport={"width":390,"height":844},is_mobile=True,has_touch=True,device_scale_factor=1)
        mobile=mobile_context.new_page()
        mobile.on("pageerror",lambda error: errors.append(str(error)))
        mobile.goto("http://127.0.0.1:5173")
        expect(mobile.get_by_role("grid")).to_be_visible()
        assert mobile.evaluate("document.documentElement.scrollWidth <= window.innerWidth"),"Mobile has horizontal overflow"
        expect(mobile.locator(".ready-overlay")).to_be_visible()
        expect(mobile.locator(".settings-win-length")).to_be_visible()
        mobile.screenshot(path=str(OUT/"mobile-ready.png"),full_page=True)
        mobile.locator(".start-button").click()
        mobile.get_by_role("gridcell",name="H8: ô trống",exact=True).click()
        expect(mobile.locator(".occupied")).to_have_count(2,timeout=15000)
        mobile.screenshot(path=str(OUT/"mobile.png"),full_page=True)
        print("PASS mobile layout and playable AI board",flush=True)
        assert not errors, json.dumps(errors,ensure_ascii=True)
        print("ALL BROWSER CHECKS PASSED; no JavaScript errors",flush=True)
        browser.close()


if __name__=="__main__":
    main()
